//just for notes for assignment operators
#include<iostream>
using namespace std;
int main()
{
    int a=10,b=20;
    cout<<"a="<<a<<endl;
    cout<<"b="<<b<<endl;
    a+=b;
    cout<<"a+=b="<<a<<endl;
    a-=b;
    cout<<"a-=b="<<a<<endl;
    a*=b;
    cout<<"a*=b="<<a<<endl;
    a/=b;
    cout<<"a/=b="<<a<<endl;
    a%=b;
    cout<<"a%=b="<<a<<endl;

}